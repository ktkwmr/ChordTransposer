#!/usr/bin/env node
// Generates the guide pages and the sitemap:
//   public/chordtransposer/<slug>/index.html     (English)
//   public/chordtransposer/ja/<slug>/index.html  (Japanese)
//   public/sitemap.xml
//
// Each page is written in scripts/pages/<slug>.mjs, with separate English and
// Japanese text (the articles are written for each language, not translated
// string by string). The shared header, footer, styles, and <head> tags are in
// scripts/pages/layout.mjs. Tables such as the capo chart are computed in
// scripts/pages/music.mjs so they cannot contain typos.
//
// To add a page: create scripts/pages/<slug>.mjs and add it to PAGES below.
//
// Usage: node scripts/build-pages.mjs [--check]
//   --check  do not write; exit 1 if a generated file is out of date.
// Runs automatically before `wrangler deploy` / `wrangler dev` (build.command in wrangler.jsonc).

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { renderPage, ORIGIN, APP_PATH, PUBLISHED, pagePath } from "./pages/layout.mjs";

// Footer order
const PAGES = ["guide", "transposition-basics", "capo-chart", "key-chart", "sharps-and-flats", "chordpro", "faq"];

const CHECK = process.argv.includes("--check");
const PUBLIC = fileURLToPath(new URL("../public/", import.meta.url));

const pages = [];
for (const slug of PAGES) {
  const mod = (await import(`./pages/${slug}.mjs`)).default;
  if (mod.slug !== slug) throw new Error(`scripts/pages/${slug}.mjs: slug is "${mod.slug}"`);
  for (const lang of ["en", "ja"]) {
    for (const key of ["title", "description", "nav", "body"]) {
      if (!mod[lang] || !mod[lang][key]) throw new Error(`scripts/pages/${slug}.mjs: ${lang}.${key} is missing`);
    }
  }
  pages.push(mod);
}

function jsonLdFor(lang, page) {
  const t = page[lang];
  const url = ORIGIN + pagePath(lang, page.slug);
  const author = { "@type": "Person", name: "ktkwmr", url: "https://github.com/ktkwmr" };
  if (page.faq) {
    return {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      url,
      inLanguage: lang,
      mainEntity: t.faq.map((qa) => ({
        "@type": "Question",
        name: qa.q,
        acceptedAnswer: { "@type": "Answer", text: qa.a.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim() },
      })),
    };
  }
  return {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: t.heading || t.title,
    description: t.description,
    url,
    inLanguage: lang,
    datePublished: page.published || PUBLISHED,
    ...(page.modified ? { dateModified: page.modified } : {}),
    author,
    publisher: author,
    image: ORIGIN + "/chordtransposer/og-image.png",
    isPartOf: { "@type": "WebSite", name: "Chord Transposer", url: ORIGIN + APP_PATH[lang] },
  };
}

const outputs = new Map();
for (const page of pages) {
  for (const lang of ["en", "ja"]) {
    const t = page[lang];
    const body = typeof t.body === "function" ? t.body() : t.body;
    const html = renderPage({ lang, page, pages, body, jsonLd: jsonLdFor(lang, page) });
    outputs.set(PUBLIC + pagePath(lang, page.slug).slice(1) + "index.html", html);
  }
}

// ---------- sitemap.xml ----------
const alternates = (enPath, jaPath) =>
  [
    `    <xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}${enPath}" />`,
    `    <xhtml:link rel="alternate" hreflang="ja" href="${ORIGIN}${jaPath}" />`,
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}${enPath}" />`,
  ].join("\n");
const urlEntries = [[APP_PATH.en, APP_PATH.ja], ...pages.map((p) => [pagePath("en", p.slug), pagePath("ja", p.slug)])]
  .flatMap(([enPath, jaPath]) =>
    [enPath, jaPath].map((loc) => `  <url>\n    <loc>${ORIGIN}${loc}</loc>\n${alternates(enPath, jaPath)}\n  </url>`)
  )
  .join("\n");
outputs.set(
  PUBLIC + "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-pages.mjs. Do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urlEntries}
</urlset>
`
);

// ---------- write ----------
let stale = 0;
for (const [file, content] of outputs) {
  let current = null;
  // Ignore CRLF line endings in a Windows checkout (Git's core.autocrlf); the output is written with LF
  try { current = (await readFile(file, "utf8")).replace(/\r\n/g, "\n"); } catch {}
  if (current === content) continue;
  stale++;
  const rel = file.slice(PUBLIC.length - "public/".length);
  if (CHECK) {
    console.error(`${rel} is out of date.`);
  } else {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
    console.log("Wrote " + rel);
  }
}
if (CHECK && stale) {
  console.error("Run: node scripts/build-pages.mjs");
  process.exit(1);
}
if (!stale) console.log(`Guide pages and sitemap.xml are up to date (${outputs.size} files).`);
